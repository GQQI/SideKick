export type MsgKey = keyof typeof zh;

const tables: Record<Locale, Record<MsgKey, string>> = { zh, en };

export function translate(locale: Locale, key: MsgKey, ...args: string[]): string {
  let s = tables[locale][key] || tables.zh[key] || key;
  args.forEach((a, i) => {
    s = s.replace(`{${i}}`, a);
  });
  return s;
}

